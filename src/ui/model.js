// "Model" tab: what the learned handwriting model found, and what it makes.
//   * overview: which characters have their own model, how much variation the
//     modes explain, and the global habits shared by sparse characters;
//   * per character: your real copies, the top variation patterns shown as
//     morphs from -2 sd to +2 sd, and a gallery of freshly generated copies.

import { h, toast } from './render.js';
import { CHARSET } from '../core/constants.js';

function inkCanvas(s, { scale = 0.42, color = '#1d2433', height = 0 } = {}) {
  const c = document.createElement('canvas');
  if (!s) return c;
  const t = document.createElement('canvas'); t.width = s.w; t.height = s.h;
  const tx = t.getContext('2d'), im = tx.createImageData(s.w, s.h);
  const r = parseInt(color.slice(1, 3), 16), g = parseInt(color.slice(3, 5), 16), b = parseInt(color.slice(5, 7), 16);
  for (let i = 0; i < s.ink.length; i++) { im.data[i * 4] = r; im.data[i * 4 + 1] = g; im.data[i * 4 + 2] = b; im.data[i * 4 + 3] = Math.min(1, s.ink[i]) * 255; }
  tx.putImageData(im, 0, 0);
  // Fixed-height frame so baselines line up across a row.
  const H = height || Math.round(s.h * scale);
  c.width = Math.max(8, Math.round(s.w * scale)); c.height = H;
  const x = c.getContext('2d');
  x.drawImage(t, 0, H * 0.72 - s.baseline * scale, s.w * scale, s.h * scale);
  return c;
}

export function viewModel(main, ctx) {
  const { state, call, busy, saveSettings, markDirty } = ctx;
  main.append(
    h('h1', {}, 'Learned handwriting model'),
    h('p', { class: 'lede' }, 'Inkforge studies every copy you wrote of each letter, finds the main ways your version of it varies (lean, loop size, width, how far strokes reach), and generates brand-new copies that vary the same way. These fill the font’s extra versions instead of simple tilted duplicates.'),
  );
  if (!state.samples.length) {
    main.append(h('div', { class: 'card empty' }, h('h2', {}, 'Nothing to learn from yet'), h('a', { class: 'btn primary', href: '#capture' }, 'Capture handwriting')));
    return;
  }
  const S = state.settings;
  const overview = h('div', { class: 'card' }, h('p', { class: 'muted' }, 'Training on your library…'));
  const detail = h('div', { class: 'card' });
  const creativity = h('input', { type: 'range', min: 0.3, max: 2, step: 0.05, value: S.creativity ?? 1 });
  const creOut = h('output', {}, (S.creativity ?? 1).toFixed(2));
  const useIt = h('input', { type: 'checkbox', checked: S.learned !== false });
  let current = null, alive = true;

  creativity.oninput = () => { creOut.textContent = Number(creativity.value).toFixed(2); };
  creativity.onchange = async () => { S.creativity = Number(creativity.value); await saveSettings(); if (current) showChar(current); };
  useIt.onchange = async () => { S.learned = useIt.checked; await saveSettings(); markDirty(); toast(useIt.checked ? 'Font will use learned copies' : 'Font will use simple variations', 'good'); };

  main.append(
    h('div', { class: 'card' }, h('div', { class: 'row spread' },
      h('label', { class: 'check' }, useIt, 'Use the learned model for the font’s extra versions'),
      h('label', { class: 'slider', style: { minWidth: '280px' } }, h('span', {}, 'Creativity'), creOut, creativity,
        h('span', { class: 'hint' }, '1 = your measured variation · lower = closer to your typical shape · higher = more adventurous')))),
    overview, detail,
  );

  async function load() {
    const t0 = performance.now();
    const rep = await call('learnReport');
    if (!alive) return;
    const secs = ((performance.now() - t0) / 1000).toFixed(1);
    const order = [...CHARSET].filter(c => rep.chars[c]);
    const chips = h('div', { class: 'coverage' }, order.map(c => {
      const e = rep.chars[c];
      const cls = e.modes ? 'have' : '';
      return h('div', { class: `cov ${cls} ${c === current ? 'sel' : ''}`, title: e.modes ? `${e.trained} copies · ${e.modes} patterns` : `${e.trained} copies · uses your general habits`, onclick: () => showChar(c) }, c, e.modes ? h('span', { class: 'n' }, e.modes) : null);
    }));
    overview.replaceChildren(
      h('div', { class: 'stats', style: { marginBottom: '10px' } },
        h('span', {}, h('b', {}, rep.stats.modelled), ' characters with their own model'),
        h('span', {}, h('b', {}, rep.stats.characters - rep.stats.modelled), ' use your general habits'),
        h('span', {}, h('b', {}, rep.stats.fieldsLearned), ' copies analysed'),
        h('span', {}, h('b', {}, rep.globalModes), ' general habit patterns'),
        h('span', {}, `trained in ${secs}s`)),
      h('p', { class: 'muted', style: { fontSize: '13px' } }, 'Green = learned from at least 3 of your copies (the number is how many patterns it found). Others are generated by applying the habits learned across all your letters to their drawings. Click any character.'),
      chips);
    if (!current) showChar(order.find(c => rep.chars[c].modes) || order[0]);
  }

  async function showChar(ch) {
    current = ch;
    for (const el of overview.querySelectorAll('.cov')) el.classList.toggle('sel', el.firstChild && el.firstChild.textContent === ch);
    detail.replaceChildren(h('p', { class: 'muted' }, `Generating “${ch}”…`));
    const T = Number(creativity.value);
    const res = await call('learnChar', { ch, count: 30, temperature: T });
    if (!alive || current !== ch) return;
    const real = state.samples.filter(s => s.char === ch && !s.disabled);
    const col = '#1d2a5a'; // rows are always light paper, so always dark ink (even in dark mode)
    const row = (list, opts) => h('div', { class: 'm-row' }, list.map(s => inkCanvas(s, { color: col, height: 80, ...opts })));
    const patterns = res.morphs.map((m, k) => h('div', { class: 'm-pattern' },
      h('div', { class: 'm-label' }, `Pattern ${k + 1}`, h('small', {}, `${Math.round(m.share * 100)}% of the variation`)),
      h('div', { class: 'm-row' }, m.frames.map(f => h('div', { class: 'm-frame' }, inkCanvas(f.s, { color: col, height: 80 }), h('small', {}, f.t === 0 ? 'typical' : `${f.t > 0 ? '+' : ''}${f.t}σ`))))));
    let page = 0;
    const gallery = row(res.gen);
    const more = h('button', { onclick: async () => {
      page++;
      const r2 = await call('learnChar', { ch, start: page * 30, count: 30, temperature: T, modes: 0 });
      for (const s of r2.gen) gallery.append(inkCanvas(s, { color: col, height: 80 }));
    } }, 'Generate 30 more');
    detail.replaceChildren(
      h('div', { class: 'row spread' }, h('h2', {}, `“${ch}”`),
        h('span', { class: 'tag' }, res.own ? `own model from ${real.filter(s => s.source !== 'fill-in').length} of your copies` : 'uses your general habits')),
      h('h3', {}, 'Your copies'),
      real.length ? row(real.slice(0, 40)) : h('p', { class: 'muted' }, 'None yet.'),
      h('h3', {}, res.own ? 'Patterns it found in your writing' : 'General habits it applies'),
      h('p', { class: 'muted', style: { fontSize: '13px' } }, 'Each row is one way your writing varies, shown from one extreme (−2σ) through typical to the other (+2σ).'),
      ...(patterns.length ? patterns : [h('p', { class: 'muted' }, 'Not enough copies to find patterns.')]),
      h('div', { class: 'row spread', style: { marginTop: '14px' } }, h('h3', { style: { margin: 0 } }, 'Generated copies'), more),
      gallery);
  }

  load().catch(e => overview.replaceChildren(h('p', { class: 'muted' }, 'Model failed: ' + e.message)));
  return () => { alive = false; };
}
